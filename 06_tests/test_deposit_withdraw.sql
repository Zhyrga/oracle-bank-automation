-- Тесты deposit и withdraw
-- Ручной тест: запускайте в одной сессии, смотрите результат и сравнивайте с комментарием «Ожидаем».
-- Процедуры пакета не делают COMMIT, поэтому в конце файла стоит ROLLBACK: данные возвращаются как были.
-- Номера счетов и балансы в комментариях взяты из тестовых данных проекта.

-- Ожидаем: баланс 1001 вырос на 1000, в transactions новая строка "Пополнение"
exec bank_pkg.deposit(1001, 1000);

--Ожидаем: ошибку ORA-20002, сумма <= 0
exec bank_pkg.deposit(1001, 0);

--Ожидаем: ошибку ORA-20003, счет не найден
exec bank_pkg.deposit(1099, 1);

--Ожидаем: баланс 158500.1 у счета 1001, в transactions новая строка "Пополнение"
exec bank_pkg.deposit(1001, 0.1);

--Ожидаем: у счета 1002 баланс 490000, в transactions новая строка "Снятие"
exec bank_pkg.withdraw(1002, 10000);

--Ожидаем: ошибку ORA-20001: на балансе недостаточно средств
exec bank_pkg.withdraw(1002, 900000);

--Ожидаем: счет 1099 не найден
exec bank_pkg.withdraw(1099, 1);

--Ожидаем: 489999.9, в transactions новая строка "Снятие"
exec bank_pkg.withdraw(1002, 0.1);

--Ожидаем: ошибку ORA-20002, сумма <= 0
exec bank_pkg.withdraw(1002, 0);

--Ожидаем: баланс 0, снимаю ровно весь баланс 84000 у счета 1003
exec bank_pkg.withdraw(1003, 84000);

--сумма меньше копейки, например deposit(1003, 0.001): баланс и транзакция хранят два знака после запятой, поэтому здесь возможна ошибка ORA-02290.
exec bank_pkg.deposit(1003, 0.001);

