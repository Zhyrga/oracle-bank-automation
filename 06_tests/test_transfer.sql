-- Проверка процедуры transfer
--Ожидаем: успешный перевод, у счета 1024 - 15000 с баланса = 0, у счета 1023 + на балансе 15000 = 515000 
 exec bank_pkg.transfer(1024, 1023, 15000);

--Ожидаем: Ошибку, недостаточно средств
exec bank_pkg.transfer(1023, 1024, 516000);

--Ожидаем: Ошибку, что самому переводить нельзя
exec bank_pkg.transfer(1023, 1023, 1000);

--Ожидаем: Ошибку, такого счета не существует и чтобы баланс у 1023 не изменился
exec bank_pkg.transfer(1023, 1090, 1000);
exec bank_pkg.transfer(1090, 1023, 1000);

--Ожидаем: На балансе 0.1 у счета 1024, в транзакции + 1 "Перевод"
exec bank_pkg.transfer(1023, 1024, 0.1);

--Ожидаем: Ошибку, сумма должна быть больше нуля
exec bank_pkg.transfer(1023, 1024, 0);

--Ожидаем: сумма должна быть больше нуля
exec bank_pkg.transfer(1023, 1024, -2);

--Ожидаем: счет не найден
exec bank_pkg.transfer(1023, null, 1000);
exec bank_pkg.transfer(null, 1023, 1000);

